def synthetic_bytes(seed: int, size=(48, 48)) -> bytes:
    rng = np.random.RandomState(seed)
    arr = (rng.rand(size[1], size[0], 3) * 255).astype("uint8")
    img = Image.fromarray(arr, "RGB")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def _row(dataset, slug, split, uuid, photo_id, sha256, species="Sp X", taxon_id="1"):
    identity = spd.row_identity(dataset, slug, split, str(photo_id))
    return {"dataset": dataset, "slug": slug, "split": split, "species": species, "taxon_id": taxon_id,
            "observation_uuid": uuid, "photo_id": str(photo_id), "sha256": sha256, "identity": identity}


