class TestScanPrePublicationValidation(_PreScanFixtureTestCase):
    """Item 1: cmd_scan must call validate_reports_against_population on
    the in-memory reports, before publish_reports_atomically, so a defect
    that structural validation alone would miss still blocks publication
    entirely (all five files, all-or-nothing) -- and a corrected later
    --scan remains possible (nothing left behind to collide with it)."""

    # Each test below intercepts _report_envelope to corrupt ONLY the
    # in-memory content of one already-assembled report (never the shared
    # `hashes`/`candidate_domains`/`rows_by_part` values pair generation
    # itself depends on, which would crash the pipeline instead of
    # exercising validation) and bypasses the pre-existing structural
    # layer (mrc.validate_scan_report_bundle) so the defect can ONLY be
    # caught by the NEW validate_reports_against_population call -- proving
    # that call is actually wired in and actually blocks publication.

    def _mutate_hashes_report(self, content):
        content = dict(content)
        hashes = dict(content["hashes"])
        del hashes[next(iter(hashes))]  # drop one real identity's hash entry
        content["hashes"] = hashes
        return content

    def _mutate_candidate_pairs_report_drop_pair(self, content):
        content = dict(content)
        domains = dict(content["domains"])
        for name, pairs in domains.items():
            if pairs:
                domains[name] = pairs[1:]  # silently drop one real candidate
                break
        content["domains"] = domains
        return content

    def _mutate_candidate_pairs_report_change_distance(self, content):
        content = dict(content)
        domains = dict(content["domains"])
        for name, pairs in domains.items():
            if pairs:
                new_pairs = list(pairs)
                new_pairs[0] = {**new_pairs[0],
                                "dhash_distance": min(new_pairs[0]["dhash_distance"] + 1, mrc.DHASH_BITS)}
                domains[name] = new_pairs
                break
        content["domains"] = domains
