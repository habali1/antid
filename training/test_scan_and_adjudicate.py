class TestIndexedEqualsBruteForce(unittest.TestCase):
    """Proves generate_candidate_pairs_indexed produces the EXACT same set
    of pairs as generate_candidate_pairs_bruteforce, across randomized
    synthetic fixtures -- both within-set (exclude_self) and cross-set."""

    def _random_hash_row(self, rng, dataset, i):
        identity = f"{dataset}:s:split:{i}"
        return identity, {
            "phashes": [rng.getrandbits(64) for _ in range(8)],
            "dhashes": [rng.getrandbits(64) for _ in range(8)],
        }

    def test_cross_set_randomized_fixture(self):
        import random
        rng = random.Random(777)
        rows_a, hashes_a = [], {}
        for i in range(15):
            identity, h = self._random_hash_row(rng, "a", i)
            rows_a.append({"identity": identity})
            hashes_a[identity] = h
        rows_b, hashes_b = [], {}
        for i in range(20):
            identity, h = self._random_hash_row(rng, "b", i)
            rows_b.append({"identity": identity})
            hashes_b[identity] = h
        # force a handful of guaranteed close pairs
        for i in range(4):
            base = hashes_a[rows_a[i]["identity"]]
            close_identity = f"b:close:{i}"
            rows_b.append({"identity": close_identity})
            hashes_b[close_identity] = {
                "phashes": [v ^ 0b111 for v in base["phashes"]],  # 3-bit flips -> within phash radius 10
                "dhashes": [rng.getrandbits(64) for _ in range(8)],
            }

        brute = spd.generate_candidate_pairs_bruteforce(rows_a, hashes_a, rows_b, hashes_b)
        indexed = spd.generate_candidate_pairs_indexed(rows_a, hashes_a, rows_b, hashes_b)
        self.assertEqual(
            {(p["identity_a"], p["identity_b"]) for p in brute},
            {(p["identity_a"], p["identity_b"]) for p in indexed},
        )
        self.assertGreater(len(brute), 0, "fixture must actually exercise some matches")
        # distances must agree exactly too
        brute_by_pair = {(p["identity_a"], p["identity_b"]): p for p in brute}
        for p in indexed:
            key = (p["identity_a"], p["identity_b"])
            self.assertEqual(p["phash_distance"], brute_by_pair[key]["phash_distance"])
            self.assertEqual(p["dhash_distance"], brute_by_pair[key]["dhash_distance"])

    def test_within_set_randomized_fixture_excludes_self_pairs(self):
        import random
        rng = random.Random(4242)
        rows, hashes = [], {}
        for i in range(25):
            identity, h = self._random_hash_row(rng, "w", i)
            rows.append({"identity": identity})
            hashes[identity] = h
        for i in range(3):
            base = hashes[rows[i]["identity"]]
            hashes[rows[i + 10]["identity"]] = {
                "phashes": [v ^ 0b11 for v in base["phashes"]],
                "dhashes": hashes[rows[i + 10]["identity"]]["dhashes"],
            }

        brute = spd.generate_candidate_pairs_bruteforce(rows, hashes, rows, hashes, exclude_self=True)
        indexed = spd.generate_candidate_pairs_indexed(rows, hashes, rows, hashes, exclude_self=True)
        self.assertEqual(
            {(p["identity_a"], p["identity_b"]) for p in brute},
            {(p["identity_a"], p["identity_b"]) for p in indexed},
        )
        for p in indexed:
            self.assertNotEqual(p["identity_a"], p["identity_b"])

    def test_real_synthetic_images_indexed_matches_bruteforce(self):
        # A small real-image fixture (not just hand-built hash ints).
        base_bytes = synthetic_bytes(1, size=(64, 64))
        base_sha = ph.sha256_bytes(base_bytes)
        row_a = _row("d1", "s1", "train", "u1", 1, base_sha)
        hashes_a = {row_a["identity"]: ph.compute_all_hashes(base_bytes, base_sha)}

        img = Image.open(io.BytesIO(base_bytes))
        buf = io.BytesIO()
        img.save(buf, format="JPEG", quality=75)
        derived_bytes = buf.getvalue()
        derived_sha = ph.sha256_bytes(derived_bytes)
        row_b1 = _row("d2", "s1", "final_test", "u1", 2, derived_sha)
        hashes_b1 = {row_b1["identity"]: ph.compute_all_hashes(derived_bytes, derived_sha)}

        other_bytes = synthetic_bytes(999, size=(64, 64))
        other_sha = ph.sha256_bytes(other_bytes)
        row_b2 = _row("d2", "s2", "final_test", "u2", 3, other_sha)
        hashes_b2 = {row_b2["identity"]: ph.compute_all_hashes(other_bytes, other_sha)}

        hashes_b = {**hashes_b1, **hashes_b2}
        brute = spd.generate_candidate_pairs_bruteforce([row_a], hashes_a, [row_b1, row_b2], hashes_b)
        indexed = spd.generate_candidate_pairs_indexed([row_a], hashes_a, [row_b1, row_b2], hashes_b)
        self.assertEqual(
            {(p["identity_a"], p["identity_b"]) for p in brute},
            {(p["identity_a"], p["identity_b"]) for p in indexed},
        )
        self.assertIn((row_a["identity"], row_b1["identity"]),
                      {(p["identity_a"], p["identity_b"]) for p in indexed})

    def test_within_set_two_row_regression_exactly_one_canonical_candidate(self):
        # Item 2: two rows, identical hashes -- the within-set search must
        # examine the one unordered pair exactly once, never emit both
        # A->B and B->A under the same pair_id.
        h = {"phashes": [0] * 8, "dhashes": [0] * 8}
        rows = [{"identity": "z-row"}, {"identity": "a-row"}]  # deliberately NOT pre-sorted
        hashes = {"z-row": h, "a-row": dict(h)}

        indexed = spd.generate_candidate_pairs_within_indexed(rows, hashes)
        self.assertEqual(len(indexed), 1)
        pair = indexed[0]
        self.assertEqual((pair["identity_a"], pair["identity_b"]), ("a-row", "z-row"))  # canonical sorted order
        self.assertEqual(pair["pair_id"], mrc.compute_pair_id("a-row", "z-row"))
        self.assertEqual(pair["phash_distance"], 0)
        self.assertEqual(pair["dhash_distance"], 0)

        # The RAW (non-canonicalized) indexed search would have produced
        # both directions under the same pair_id -- prove that's exactly
        # what canonicalization collapsed.
        raw = spd.generate_candidate_pairs_indexed(rows, hashes, rows, hashes, exclude_self=True)
        self.assertEqual(len(raw), 2)
        self.assertEqual({p["pair_id"] for p in raw}, {pair["pair_id"]})

    def test_within_set_indexed_matches_bruteforce_under_unordered_semantics(self):
        import random
        rng = random.Random(9191)
        rows, hashes = [], {}
        for i in range(20):
            identity, h = self._random_hash_row(rng, "w", i)
            rows.append({"identity": identity})
            hashes[identity] = h
        for i in range(4):
            base = hashes[rows[i]["identity"]]
            hashes[rows[i + 10]["identity"]] = {
                "phashes": [v ^ 0b11 for v in base["phashes"]],
                "dhashes": hashes[rows[i + 10]["identity"]]["dhashes"],
            }

        brute = spd.generate_candidate_pairs_within_bruteforce(rows, hashes)
        indexed = spd.generate_candidate_pairs_within_indexed(rows, hashes)
        self.assertEqual(brute, indexed)  # exact equality: same pair_ids, same canonical order, same distances
        self.assertGreater(len(indexed), 0, "fixture must actually exercise some matches")
        # No pair_id appears more than once (unordered semantics honored).
        pair_ids = [p["pair_id"] for p in indexed]
        self.assertEqual(len(pair_ids), len(set(pair_ids)))
        for p in indexed:
            self.assertLess(p["identity_a"], p["identity_b"])


