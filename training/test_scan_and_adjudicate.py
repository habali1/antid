class TestPublishReportsAtomically(_ScanFixtureTestCase):
    def test_publishes_all_files_together(self):
        dest_a = self.repo / "a.json"
        dest_b = self.repo / "b.json"
        spd.publish_reports_atomically({dest_a: b'{"x":1}', dest_b: b'{"y":2}'})
        self.assertTrue(dest_a.exists())
        self.assertTrue(dest_b.exists())

    def test_refuses_to_overwrite_existing(self):
        dest_a = self.repo / "a.json"
        dest_a.write_bytes(b"existing")
        with self.assertRaises(spd.ScanError):
            spd.publish_reports_atomically({dest_a: b'{"x":1}'})
        self.assertEqual(dest_a.read_bytes(), b"existing")

    def test_failure_on_second_file_rolls_back_the_first(self):
        dest_a = self.repo / "sub" / "a.json"
        dest_b = self.repo / "sub" / "b.json"
        real_link = spd.os.link
        call_count = {"n": 0}

        def flaky_link(src, dst):
            call_count["n"] += 1
            if call_count["n"] == 2:
                raise OSError("injected")
            return real_link(src, dst)

        with mock.patch.object(spd.os, "link", side_effect=flaky_link):
            with self.assertRaises(OSError):
                spd.publish_reports_atomically({dest_a: b"1", dest_b: b"2"})
        self.assertFalse(dest_a.exists())
        self.assertFalse(dest_b.exists())
        leftovers = list((self.repo / "sub").glob("*.tmp*"))
        self.assertEqual(leftovers, [])


class _RealScanFixtureTestCase(unittest.TestCase):
    """A tiny but REAL fixture: real decodable synthetic images (never a
    real dataset photograph), real sha256 values matching them, one forced
    guaranteed perceptual duplicate across expansion_train/final_test, and
    a real cmd_scan() run producing all five reports (published atomically
    to disk, then re-loadable exactly like the real (never-run-here)
    pipeline would)."""

    def setUp(self):
        self._tmpdir = tempfile.TemporaryDirectory()
        self.repo = Path(self._tmpdir.name)
        self.fx = build_tiny_review_fixture(self, self.repo, slugs=("fx-species-a",), n_final_test=2,
                                            per_slug=1, per_bucket=2, real_images=True)
        self.verified = mrc.load_and_verify_contract(self.repo)
        self.scan_result = spd.cmd_scan(self._args())

    def tearDown(self):
        self._tmpdir.cleanup()

    def _args(self, **overrides):
        d = dict(repo=self.repo)
        d.update(overrides)
        return argparse.Namespace(**d)

    def _report_paths(self) -> dict[str, Path]:
        return {name: self.repo / mrc.APPROVED_OUTPUT_PATHS[name] for name in mrc.SCAN_REPORT_NAMES}

    def _load_reports(self) -> dict[str, dict]:
        return {name: json.loads(p.read_text(encoding="utf-8")) for name, p in self._report_paths().items()}

    def _rechain_and_write(self, reports: dict) -> None:
        """After mutating perceptual_hashes_report and/or
        metadata_leakage_report and/or candidate_pairs_report content,
        propagate fresh content_sha256 values through every downstream
        cross-report binding and rewrite all five files -- so the schema/
        binding layer (mrc.validate_scan_report_bundle) stays internally
        self-consistent and ONLY validate_reports_against_population's
        re-derivation against the real frozen manifests can catch the
        planted defect."""
        hashes_report = reports["perceptual_hashes_report"]
        hashes_report["content_sha256"] = mrc.compute_content_sha256(hashes_report["content"])

        cp_report = reports["candidate_pairs_report"]
        cp_report["content"]["hashes_report_content_sha256"] = hashes_report["content_sha256"]
        cp_report["content_sha256"] = mrc.compute_content_sha256(cp_report["content"])

        leakage_report = reports["metadata_leakage_report"]
        leakage_report["content_sha256"] = mrc.compute_content_sha256(leakage_report["content"])

        ds_report = reports["domain_summary_report"]
        ds_report["content"]["candidate_pairs_report_content_sha256"] = cp_report["content_sha256"]
        ds_report["content"]["metadata_leakage_report_content_sha256"] = leakage_report["content_sha256"]
        ds_report["content_sha256"] = mrc.compute_content_sha256(ds_report["content"])

        ss_report = reports["stop_status_report"]
        ss_report["content"]["domain_summary_report_content_sha256"] = ds_report["content_sha256"]
        ss_report["content_sha256"] = mrc.compute_content_sha256(ss_report["content"])

        for name, path in self._report_paths().items():
            path.write_text(json.dumps(reports[name], indent=2, sort_keys=True) + "\n", encoding="utf-8")


